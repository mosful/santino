const path = require("node:path");
const base = process.env.SANTINO_PREVIEW_BASE_URL || "http://localhost:4310";
let activeBrowser;
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
(async () => {
  const output = path.join(process.env.SANTINO_QA_OUTPUT || path.resolve("test-results"), "care_settings"); await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true }); activeBrowser = browser; const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => {
    localStorage.setItem("santino_auth_v1", "1");
    if (!localStorage.getItem("santino_current_role_v1")) localStorage.setItem("santino_current_role_v1", "管理者");
    localStorage.setItem("santino_assessment_fields_v1", JSON.stringify([{ id: "qa-custom", section: "TOCC", label: "自訂追蹤內容", type: "text", options: [], required: true }]));
    localStorage.setItem("santino_phrase_library_v1", JSON.stringify([{ id: 999, category: "照顧重點", tags: ["測試"], text: "管理端片語連動測試" }]));
  });
  const page = await context.newPage(); const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(base + "/mama/");
  await page.getByLabel("退房回補天數", { exact: true }).fill("7");
  await page.getByRole("button", { name: "入住評估", exact: true }).first().click();
  await page.getByRole("button", { name: "常用片語", exact: true }).click();
  await page.getByRole("button", { name: "管理端片語連動測試", exact: true }).click();
  assert.match(await page.getByLabel("入住護理紀錄（必填）", { exact: true }).inputValue(), /管理端片語連動測試/);
  await page.getByRole("button", { name: "TOCC", exact: true }).click();
  await page.getByLabel("自訂追蹤內容（必填）", { exact: true }).fill("自訂題目保存");
  await page.getByRole("button", { name: "暫存", exact: true }).click(); await page.reload();
  assert.equal(await page.getByLabel("自訂追蹤內容（必填）", { exact: true }).inputValue(), "自訂題目保存");
  await page.getByRole("button", { name: "完成簽出", exact: true }).click();
  await page.getByLabel("頁內操作確認").getByRole("button", { name: "確認", exact: true }).click();
  await page.getByText("已簽出紀錄（1）", { exact: true }).waitFor();
  const care = await page.evaluate(() => JSON.parse(localStorage.getItem("santino_care_workspace_v1")));
  assert.equal(care.backfillDays, 7); assert.match(care.entries[0].staffStamp.author, /管理者/);
  assert.equal(care.entries[0].values["configured-qa-custom"], "自訂題目保存");
  await page.getByRole("button", { name: "回照護列表", exact: true }).click();
  await page.getByRole("button", { name: "持續護理", exact: true }).first().click();
  await page.getByRole("button", { name: "暫存", exact: true }).click();
  await page.evaluate(() => scrollTo(0, 650)); await page.waitForTimeout(350);
  const before = await page.evaluate(() => scrollY); await page.reload(); await page.waitForTimeout(350);
  const after = await page.evaluate(() => scrollY); assert.ok(Math.abs(before - after) < 40, `捲動位置 ${before} → ${after}`);
  await page.getByTitle("切換模擬角色，選單會依該角色權限立即隱藏或顯示", { exact: true }).click();
  await page.getByRole("button", { name: /^櫃台/ }).click();
  const switched = await page.evaluate(() => JSON.parse(localStorage.getItem("santino_care_workspace_v1")));
  assert.equal(switched.unlockedCase, null); assert.equal(switched.open.length, 0); assert.ok(Object.keys(switched.documents).length > 0);
  assert.deepEqual(errors, []);
  const result = { checks: ["自訂題目／必要驗證來源", "管理端片語來源", "區段重整恢復", "可設定回補天數", "實際員工印章", "捲動位置恢復", "切換角色釋鎖保留草稿"], before, after, errors };
  await fs.writeFile(`${output}/result.json`, JSON.stringify(result, null, 2)); console.log(JSON.stringify(result)); await browser.close();
})().catch(async (error) => { console.error(error); await activeBrowser?.close(); process.exitCode = 1; });
